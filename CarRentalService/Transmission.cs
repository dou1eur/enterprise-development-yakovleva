namespace CarRentalService.Domain;
/// <summary>
/// Type of vehicle transmission
/// </summary>
public enum Transmission
{
    /// <summary>
    /// Manual transmission
    /// </summary>
    Manual,

    /// <summary>
    /// Automatic transmission
    /// </summary>
    Automatic,

    /// <summary>
    /// Continuously variable transmission
    /// </summary>
    CVT,

    /// <summary>
    /// Automated manual transmission
    /// </summary>
    AMT,

    /// <summary>
    /// Dual-Clutch transmission
    /// </summary>
    DCT
}
